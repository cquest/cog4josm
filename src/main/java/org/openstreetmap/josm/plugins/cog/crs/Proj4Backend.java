package org.openstreetmap.josm.plugins.cog.crs;

import java.math.BigDecimal;

import org.locationtech.proj4j.BasicCoordinateTransform;
import org.locationtech.proj4j.CRSFactory;
import org.locationtech.proj4j.CoordinateReferenceSystem;
import org.locationtech.proj4j.CoordinateTransform;
import org.locationtech.proj4j.Proj4jException;
import org.locationtech.proj4j.ProjCoordinate;
import org.openstreetmap.josm.plugins.cog.reader.CustomCrs;

/**
 * proj4j fallback backend (phase 2.2): projection models that the in-house
 * {@code crs/} classes do not cover, built from the GeoTIFF GeoKeys "user
 * defined" parameters (no EPSG database lookup, no WKT parsing).
 *
 * Accuracy policy: a model is routed here only when this proj4j port was
 * verified (Proj4BackendTest, anchors generated by GDAL/PROJ) to agree with
 * PROJ within a millimetre. Methods where proj4j's formulas drift from PROJ
 * were measured and stay explicitly rejected: equidistant conic (3075=13),
 * Mercator with standard parallel (3075=7), polyconic (3075=22), orthographic
 * (3075=21), stereographic declared by lat_ts instead of the scale factor,
 * and every Hotine oblique Mercator variant except the 90/90 form (9815 with
 * GeoKeys 3094=3096=90, which is the oblique stereographic of the Swiss grid,
 * implemented by proj4j "somerc").
 *
 * Two proj4j traps, both covered by tests:
 * <ul>
 *   <li>{@code +rf}/{@code +f} parameters are NOT parsed like PROJ (they
 *       corrupt the ellipsoid): the ellipsoid is always passed as explicit
 *       {@code +a}/{@code +b} computed from the plugin's own Ellipsoid;</li>
 *   <li>ellipsoid names (ellps=) differ from PROJ's table: never used;</li>
 *   <li>on a sphere (1/f = 0) the proj4j forward matches PROJ but the Albers
 *       inverse drifts by whole degrees: spheres are rejected outright.</li>
 * </ul>
 *
 * The datum stays "first order" (no towgs84 shift), same documented accuracy
 * as the in-house projections.
 */
final class Proj4Backend {

    private Proj4Backend() {
    }

    /** True when this method code (GeoKey 3075, GDAL table) maps to a verified model. */
    static boolean supports(int method) {
        return switch (method) {
            case CustomCrs.M_LAMBERT_AZIMUTHAL_EQUAL_AREA, CustomCrs.M_ALBERS_EQUAL_AREA,
                    CustomCrs.M_STEREOGRAPHIC, CustomCrs.M_POLAR_STEREOGRAPHIC,
                    CustomCrs.M_CYLINDRICAL_EQUAL_AREA, CustomCrs.M_HOTINE_OBLIQUE_MERCATOR -> true;
            default -> false;
        };
    }

    /**
     * Builds the projection from the custom GeoKeys. Linear parameters
     * (false easting/northing) are declared in the projection linear units
     * (GeoKey 3076): they are converted to metres by {@code unitFactor} so
     * that proj4j, which always works in metres, receives the right values.
     *
     * @throws IllegalArgumentException when the keys are incomplete, describe an
     *         unmapped model, or proj4j refuses the parameters
     */
    static Projection create(CustomCrs c, int method, Ellipsoid ell, double unitFactor) {
        if (ell.inverseFlattening == 0.0) {
            // measured: proj4j forward is exact on a sphere but the aea
            // INVERSE formulas drift from PROJ by whole degrees; the tile
            // warp needs the inverse, so spheres stay out of this backend
            throw new IllegalArgumentException("sphere ellipsoid (1/f = 0): the proj4j"
                    + " inverse of these models is not verified against PROJ");
        }
        StringBuilder sb = new StringBuilder();
        switch (method) {
            case CustomCrs.M_ALBERS_EQUAL_AREA: {
                sb.append("+proj=aea");
                angle(c, sb, " +lat_1=", CustomCrs.KEY_PROJ_STD_PARALLEL1, 90.0);
                angle(c, sb, " +lat_2=", CustomCrs.KEY_PROJ_STD_PARALLEL2, 90.0);
                eitherAngle(c, sb, " +lat_0=", CustomCrs.KEY_PROJ_ORIG_LAT,
                        CustomCrs.KEY_PROJ_FALSE_ORIGIN_LAT, 90.0);
                eitherAngle(c, sb, " +lon_0=", CustomCrs.KEY_PROJ_CENT_MERIDIAN,
                        CustomCrs.KEY_PROJ_FALSE_ORIGIN_LONG, 180.0);
                break;
            }
            case CustomCrs.M_LAMBERT_AZIMUTHAL_EQUAL_AREA: {
                sb.append("+proj=laea");
                angle(c, sb, " +lat_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LAT, 90.0);
                angle(c, sb, " +lon_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LONG, 180.0);
                break;
            }
            case CustomCrs.M_STEREOGRAPHIC: {
                // GDAL form: natural origin + scale factor (never lat_ts, whose
                // proj4j port drifts from PROJ)
                sb.append("+proj=stere");
                Double natLat = c.dbl(CustomCrs.KEY_PROJ_NAT_ORIGIN_LAT);
                angle(c, sb, " +lat_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LAT, 90.0);
                if (natLat != null && Double.isFinite(natLat) && Math.abs(natLat) >= 90.0 - 1e-9) {
                    // measured: at a pole with a scale factor only, proj4j and
                    // PROJ disagree; a polar system must declare its standard
                    // parallel (GDAL writes method 3075=21 for those)
                    throw new IllegalArgumentException("stereographic natural origin at a"
                            + " pole with a scale factor (3092): PROJ and proj4j disagree,"
                            + " the polar form needs a standard parallel");
                }
                angle(c, sb, " +lon_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LONG, 180.0);
                scale(c, sb, " +k_0=", CustomCrs.KEY_PROJ_SCALE_FACTOR, 1.0);
                break;
            }
            case CustomCrs.M_POLAR_STEREOGRAPHIC: {
                // GeoKeys do not store the latitude of natural origin: it is
                // the pole, whose sign only follows the sign of the standard
                // parallel (GeoKey 3081); 3081 = 0 leaves the pole unknown.
                Double latTs = c.dbl(CustomCrs.KEY_PROJ_ORIG_LAT);
                if (latTs == null || !Double.isFinite(latTs)) {
                    throw new IllegalArgumentException(
                            "GeoKey 3081 (DOUBLE) missing or invalid");
                }
                if (Math.abs(latTs) > 90.0) {
                    throw new IllegalArgumentException(
                            "polar stereographic standard parallel (3081) out of range: " + latTs);
                }
                if (Math.abs(latTs) < 1e-12) {
                    throw new IllegalArgumentException("polar stereographic standard parallel"
                            + " (3081) is 0: the GeoKeys do not say which pole");
                }
                sb.append("+proj=stere +lat_0=").append(latTs > 0 ? "90" : "-90");
                sb.append(" +lat_ts=").append(num(latTs));
                Double lon0 = c.dbl(CustomCrs.KEY_PROJ_CENTER_LONG);
                if (lon0 != null && !Double.isFinite(lon0)) {
                    throw new IllegalArgumentException("GeoKey 3095 (DOUBLE) invalid");
                }
                sb.append(" +lon_0=").append(num(lon0 == null ? 0.0 : lon0));
                // the polar model is defined by its standard parallel: a scale
                // factor (3092) combined with lat_ts was never verified against
                // PROJ, only the k = 1 form GDAL writes
                Double k = c.dbl(CustomCrs.KEY_PROJ_SCALE_FACTOR);
                if (k != null && !Double.isFinite(k)) {
                    throw new IllegalArgumentException("GeoKey 3092 (DOUBLE) invalid");
                }
                if (k != null && Math.abs(k - 1.0) > 1e-9) {
                    throw new IllegalArgumentException("polar stereographic scale factor (3092) = "
                            + k + ": only the lat_ts-defined form (k = 1) is verified");
                }
                sb.append(" +k_0=1");
                break;
            }
            case CustomCrs.M_CYLINDRICAL_EQUAL_AREA: {
                sb.append("+proj=cea");
                angle(c, sb, " +lat_ts=", CustomCrs.KEY_PROJ_STD_PARALLEL1, 90.0);
                angle(c, sb, " +lon_0=", CustomCrs.KEY_PROJ_CENT_MERIDIAN, 180.0);
                break;
            }
            case CustomCrs.M_HOTINE_OBLIQUE_MERCATOR: {
                Double az = c.dbl(CustomCrs.KEY_PROJ_AZIMUTH);
                Double rg = c.dbl(CustomCrs.KEY_PROJ_RECT_GRID_ANGLE);
                boolean obliqueStere = az != null && rg != null
                        && Double.isFinite(az) && Double.isFinite(rg)
                        && Math.abs(az - 90.0) <= 1e-9 && Math.abs(rg - 90.0) <= 1e-9;
                if (!obliqueStere) {
                    throw new IllegalArgumentException("oblique Mercator azimuth/angle combo ("
                            + az + ", " + rg + ") cannot be mapped to proj4j without risk:"
                            + " only the 90/90 oblique stereographic form is accepted");
                }
                sb.append("+proj=somerc");
                angle(c, sb, " +lat_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LAT, 90.0);
                angle(c, sb, " +lon_0=", CustomCrs.KEY_PROJ_NAT_ORIGIN_LONG, 180.0);
                scale(c, sb, " +k_0=", CustomCrs.KEY_PROJ_SCALE_AT_CENTER, 1.0);
                break;
            }
            default:
                throw new IllegalArgumentException("no proj4j model for method " + method);
        }
        // false easting/northing: generic keys first, false-origin group as
        // fallback (hybrid writers), default 0 (as PROJ itself); the GeoKey
        // values are in the projection linear units, proj4j wants metres
        linear(c, sb, " +x_0=", CustomCrs.KEY_PROJ_FALSE_EASTING,
                CustomCrs.KEY_PROJ_FALSE_ORIGIN_EASTING, 0.0, unitFactor);
        linear(c, sb, " +y_0=", CustomCrs.KEY_PROJ_FALSE_NORTHING,
                CustomCrs.KEY_PROJ_FALSE_ORIGIN_NORTHING, 0.0, unitFactor);
        // proj4j parses +rf/+f differently than PROJ: pass the semi-minor axis
        double b = ell.semiMajorAxis * (1.0 - ell.flattening);
        sb.append(" +a=").append(num(ell.semiMajorAxis)).append(" +b=").append(num(b));
        return new Proj4Projection(sb.toString());
    }

    /** Required angle parameter (degrees), |value| <= limit (90 latitudes, 180 longitudes). */
    private static void angle(CustomCrs c, StringBuilder sb, String name, int key, double limit) {
        Double v = c.dbl(key);
        if (v == null || !Double.isFinite(v) || Math.abs(v) > limit) {
            throw new IllegalArgumentException("GeoKey " + key + " (angle, DOUBLE) missing,"
                    + " invalid or out of range: " + v);
        }
        sb.append(name).append(num(v));
    }

    /** Required angle taken from the first of two equivalent keys. */
    private static void eitherAngle(CustomCrs c, StringBuilder sb, String name, int key1, int key2,
            double limit) {
        Double v = c.dbl(key1);
        if (v == null || !Double.isFinite(v)) {
            v = c.dbl(key2);
        }
        if (v == null || !Double.isFinite(v) || Math.abs(v) > limit) {
            throw new IllegalArgumentException("GeoKey " + key1 + "/" + key2
                    + " (angle, DOUBLE) missing, invalid or out of range: " + v);
        }
        sb.append(name).append(num(v));
    }

    private static void scale(CustomCrs c, StringBuilder sb, String name, int key, double deflt) {
        Double v = c.dbl(key);
        if (v == null || !Double.isFinite(v)) {
            v = deflt;
        }
        if (v <= 0.0) {
            throw new IllegalArgumentException("scale factor GeoKey " + key + " invalid: " + v);
        }
        sb.append(name).append(num(v));
    }

    private static void linear(CustomCrs c, StringBuilder sb, String name, int key1, int key2,
            double deflt, double unitFactor) {
        Double v = c.dbl(key1);
        if (v == null || !Double.isFinite(v)) {
            v = c.dbl(key2);
        }
        if (v == null || !Double.isFinite(v)) {
            v = deflt;
        }
        sb.append(name).append(num(v * unitFactor));
    }

    /**
     * Projection from a parameter string rebuilt by {@link JosmEpsgTable}
     * (explicit +a/+b, whitelisted model): same verification policy as the
     * GeoKeys path - the model whitelist is enforced by the caller, the
     * sphere ban by this method.
     */
    static Projection fromTableDef(String projDef, Ellipsoid ell) {
        if (ell.inverseFlattening == 0.0) {
            throw new IllegalArgumentException("sphere ellipsoid (1/f = 0): the proj4j"
                    + " inverse of these models is not verified against PROJ");
        }
        return new Proj4Projection(projDef);
    }

    /** Exact decimal form: never scientific notation (a "E+" would break the proj4 token parsing). */
    static String num(double v) {
        return new BigDecimal(Double.toString(v)).stripTrailingZeros().toPlainString();
    }

    /** Projection pair (WGS84-style geographic, same ellipsoid, no datum shift). */
    private static final class Proj4Projection implements Projection {

        private final CoordinateTransform forward;
        private final CoordinateTransform inverse;

        Proj4Projection(String projDef) {
            CRSFactory factory = new CRSFactory();
            String ellPart = projDef.substring(projDef.indexOf(" +a="));
            CoordinateReferenceSystem geo;
            CoordinateReferenceSystem prj;
            try {
                geo = factory.createFromParameters("cog-geodetic", "+proj=longlat" + ellPart);
                prj = factory.createFromParameters("cog-crs", projDef);
            } catch (RuntimeException e) { // Proj4jException extends RuntimeException
                throw new IllegalArgumentException("proj4 backend rejected the parameters ["
                        + projDef + "]: " + e.getMessage(), e);
            }
            forward = new BasicCoordinateTransform(geo, prj);
            inverse = new BasicCoordinateTransform(prj, geo);
        }

        @Override
        // synchronized: the underlying proj4j projections are stateful and the
        // tile workers call them concurrently
        public synchronized double[] project(double lat, double lon) {
            try {
                ProjCoordinate out = forward.transform(new ProjCoordinate(lon, lat),
                        new ProjCoordinate());
                if (!Double.isFinite(out.x) || !Double.isFinite(out.y)) {
                    return new double[]{Double.NaN, Double.NaN};
                }
                return new double[]{out.x, out.y};
            } catch (Proj4jException e) {
                return new double[]{Double.NaN, Double.NaN};
            }
        }

        @Override
        public synchronized double[] unproject(double x, double y) {
            try {
                ProjCoordinate out = inverse.transform(new ProjCoordinate(x, y),
                        new ProjCoordinate());
                if (!Double.isFinite(out.x) || !Double.isFinite(out.y)) {
                    return new double[]{Double.NaN, Double.NaN};
                }
                return new double[]{out.y, out.x};
            } catch (Proj4jException e) {
                return new double[]{Double.NaN, Double.NaN};
            }
        }

        @Override
        public int epsg() {
            return 0;
        }
    }
}
